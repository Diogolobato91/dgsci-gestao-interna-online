-- Publicações públicas e módulos operacionais que antes estavam pendentes.

grant select on table public.publications to anon, authenticated;
grant insert, update, delete on table public.publications to authenticated;

create table if not exists public.operational_cases (
  id uuid primary key default gen_random_uuid(),
  case_number bigint generated by default as identity,
  kind text not null check (kind in ('project', 'infraction', 'technical_committee')),
  subject text not null check (length(trim(subject)) between 3 and 240),
  requester_name text not null default '' check (length(requester_name) <= 180),
  cnpj text not null default '' check (cnpj = '' or cnpj ~ '^[0-9]{14}$'),
  reference text not null default '' check (length(reference) <= 120),
  status text not null default 'open' check (status in ('open', 'in_review', 'waiting', 'approved', 'rejected', 'closed')),
  assigned_to text not null default '' check (length(assigned_to) <= 180),
  notes text not null default '' check (length(notes) <= 8000),
  outcome text not null default '' check (length(outcome) <= 8000),
  opened_on date not null default current_date,
  decided_on date,
  created_by uuid not null default auth.uid() references auth.users(id),
  updated_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  version integer not null default 1 check (version > 0),
  unique (kind, case_number)
);

create index if not exists operational_cases_kind_status on public.operational_cases(kind, status, opened_on desc);
create index if not exists operational_cases_cnpj on public.operational_cases(cnpj) where cnpj <> '';

alter table public.operational_cases enable row level security;
revoke all on table public.operational_cases from public, anon, authenticated;
grant select, insert, update on table public.operational_cases to authenticated;
grant usage, select on sequence public.operational_cases_case_number_seq to authenticated;

create or replace function private.operational_case_access(p_kind text, p_write boolean default false)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.app_members m
    where m.user_id = auth.uid()
      and m.enabled
      and (
        (m.role = 'administrator' and array['Vistoriador','Análise','Multas','Secretaria','Subdiretoria','Diretoria']::text[] <@ m.sectors)
        or (p_kind = 'project' and m.sectors && array['Análise','Subdiretoria','Diretoria']::text[])
        or (p_kind = 'infraction' and m.sectors && array['Multas','Subdiretoria','Diretoria']::text[])
        or (p_kind = 'technical_committee' and m.sectors && array['Subdiretoria','Diretoria']::text[])
      )
  );
$$;

revoke all on function private.operational_case_access(text, boolean) from public, anon, authenticated;
grant execute on function private.operational_case_access(text, boolean) to authenticated;

create policy operational_cases_read
on public.operational_cases for select to authenticated
using (private.operational_case_access(kind, false));

create policy operational_cases_insert
on public.operational_cases for insert to authenticated
with check (created_by = auth.uid() and updated_by = auth.uid() and private.operational_case_access(kind, true));

create policy operational_cases_update
on public.operational_cases for update to authenticated
using (private.operational_case_access(kind, true))
with check (private.operational_case_access(kind, true));

create or replace function private.prepare_operational_case_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.kind <> old.kind or new.case_number <> old.case_number or new.created_by <> old.created_by or new.created_at <> old.created_at then
    raise exception 'Os identificadores do processo não podem ser alterados.' using errcode = '22023';
  end if;
  if new.version <> old.version then
    raise exception 'O processo foi atualizado por outra pessoa.' using errcode = '40001';
  end if;
  new.version := old.version + 1;
  new.updated_by := auth.uid();
  new.updated_at := clock_timestamp();
  if new.status in ('approved', 'rejected', 'closed') and new.decided_on is null then
    new.decided_on := current_date;
  elsif new.status not in ('approved', 'rejected', 'closed') then
    new.decided_on := null;
  end if;
  return new;
end;
$$;

revoke all on function private.prepare_operational_case_update() from public, anon, authenticated;
drop trigger if exists prepare_operational_case_update on public.operational_cases;
create trigger prepare_operational_case_update
before update on public.operational_cases
for each row execute function private.prepare_operational_case_update();

do $$
begin
  if to_regprocedure('private.capture_audit_event()') is not null then
    execute 'create trigger capture_audit_event after insert or update or delete on public.operational_cases for each row execute function private.capture_audit_event()';
  end if;
exception when duplicate_object then null;
end $$;

comment on table public.operational_cases is 'Projetos, autos de infração e processos da Comissão Técnica.';

create table if not exists private.client_error_events (
  id bigint generated always as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  source text not null check (length(source) between 1 and 300),
  message text not null check (length(message) between 1 and 1000),
  context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default clock_timestamp()
);

revoke all on table private.client_error_events from public, anon, authenticated;

create or replace function public.log_client_error(p_source text, p_message text, p_context jsonb default '{}'::jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then return; end if;
  if not exists(select 1 from public.app_members where user_id = auth.uid() and enabled) then return; end if;
  insert into private.client_error_events(user_id, source, message, context)
  values(auth.uid(), left(coalesce(nullif(btrim(p_source), ''), 'interface'), 300), left(coalesce(nullif(btrim(p_message), ''), 'Falha sem mensagem'), 1000), coalesce(p_context, '{}'::jsonb));
end;
$$;

revoke all on function public.log_client_error(text, text, jsonb) from public, anon, authenticated;
grant execute on function public.log_client_error(text, text, jsonb) to authenticated;
